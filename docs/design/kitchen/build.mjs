// #239: writes the kitchen theme (assets/themes/kitchen/: sprites.svg, scene.svg, theme.json, to #241's contract,
// docs/themes.md) from art.mjs, and the icon SVGs that shoot.sh turns into PNGs. `node docs/design/kitchen/build.mjs`
import { writeFileSync, mkdirSync } from 'node:fs';
import { ACTIONS, TICKET, ROW, LOOKS, MOMENTS, SAYS, bubble, draw, station, icon, favicon } from './art.mjs';

const out = new URL('../../../assets/themes/kitchen/', import.meta.url);
mkdirSync(out, { recursive: true });
// herd.css styles the frames and heat layers by these class names (k-prefixed, so nothing else on the page matches).
const K = { f1: 'kf1', f2: 'kf2', steam: 'ksteam', glow: 'kglow', smoke: 'ksmoke', fl: 'kfl' };
const cls = s => s.replace(/class="([^"]*)"/g, (_, c) => `class="${c.split(' ').map(t => K[t] || t).join(' ')}"`);
// One <g id> per sprite in the farm's 132 × 100 box; a 16 px row sprite fills its height, centred.
const g = (id, body) => `<g id="${id}" shape-rendering="crispEdges">${cls(body)}</g>\n`;
const row = m => `<g transform="translate(16 0) scale(6.25)">${draw(m, 1)}</g>`;
const red = '--tp:#f6d9d3;--th:#b3261e;--tl:#d89a90';
let sprites = '<!-- herdsman #239 kitchen: pixel chefs, 132 x 100 (one pixel = 4), generated by docs/design/kitchen/build.mjs from art.mjs. Looks are CSS vars: --sk/--ss skin, --hr hair, --ap/--as apron, --hc/--hs hat, --ht/--hb/--hk which hat, --fk the project neckerchief; --f1/--f2 flame; kf1/kf2 the two frames of a loop. -->\n';
for (const [k, f] of Object.entries(ACTIONS)) sprites += g(`chef-${k}`, draw(f()));
sprites += g('chef-ticket', draw(TICKET())) + g('chef-ticket-n', `<g style="${red}">${draw(TICKET())}</g>`);
for (const [k, f] of Object.entries(MOMENTS)) sprites += g(k, draw(f()) + bubble(SAYS[k]));
for (const [k, m] of Object.entries(ROW)) sprites += g(`row-${k}`, row(m));
writeFileSync(new URL('sprites.svg', out), sprites);
writeFileSync(new URL('scene.svg', out), cls(station()).replace('<svg ', '<svg xmlns="http://www.w3.org/2000/svg" '));

const theme = {
  actions: { impl: 'chef-cook', fix: 'chef-chop', rev: 'chef-taste', update: 'chef-carry', idle: 'chef-wait', done: 'chef-serve', blocked: 'chef-bell' },
  poses: { working: 'chef-cook', idle: 'chef-wait', done: 'chef-serve', blocked: 'chef-bell' },
  looks: LOOKS.map(l => Object.fromEntries(Object.entries(l.vars).map(([k, v]) => [k, String(v)]))),
  load_scene: { kind: 'heat', levels: { calm: 'simmer', busy: 'boil', held: 'flare-up' }, fan: 'chef-fan' },
  rail: { item: 'chef-ticket', needs: 'chef-ticket-n' },
  moments: { merged: { sprite: 'order-up', anim: 'hop' }, fail: { sprite: 'sent-back', anim: 'shake' }, 'needs-you': { sprite: 'chef-ticket-n', anim: 'pulse' } },
  row_sprites: { impl: 'row-cook', fix: 'row-chop', rev: 'row-taste', update: 'row-carry', idle: 'row-wait', done: 'row-serve', blocked: 'row-bell' },
  icons: { 180: 'icon-180.png', 192: 'icon-192.png', 512: 'icon-512.png', favicon: 'icon-192.png' },
  ascii: { impl: '♨\ncook', fix: '♨\nchop', rev: '♨\ntaste', update: '♨\ncarry', idle: '·\nwait', done: '✓\nserve', blocked: '!\nbell' },
  modes: ['scene', 'ascii'],
  glyphs: { working: '♨', idle: '·', unknown: '?', parked: '·', done: '✓', blocked: '!', dead: '✗' },
  words: {
    horse: 'chef', horses: 'chefs', herd: 'kitchen line', ranch: 'kitchen', barn: 'kitchen',
    impl: 'cook', fix: 'chop', rev: 'taste', update: 'carry',
    queued: 'tickets', working: 'on the line', idle: 'standing by', done: 'at the pass', 'blocked/dead': 'the bell',
  },
  scene: {
    weather: false, line: true,
    palette: {
      '--pa': 'repeating-conic-gradient(#4a3f38 0 25%,#41372f 0 50%) 0 0/24px 24px', '--sky1': '#3a332e', '--sky2': '#3a332e',
      '--fp': '#8d9399', '--fr': '#c9ced2', '--done': '1', '--blocked': 'none', '--qw': '88px',
      '--flutter': 'kflut 1.6s ease-in-out infinite alternate',
    },
  },
};
writeFileSync(new URL('theme.json', out), JSON.stringify(theme, null, 1) + '\n');

mkdirSync(new URL('./icon/', import.meta.url), { recursive: true });
for (const n of [180, 192, 512]) writeFileSync(new URL(`icon/icon-${n}.svg`, import.meta.url), icon(n));
writeFileSync(new URL('icon/favicon.svg', import.meta.url), favicon(32));
console.log('wrote assets/themes/kitchen/{sprites.svg,scene.svg,theme.json} and icon/*.svg');
