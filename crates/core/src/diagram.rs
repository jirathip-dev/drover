use crate::config::{Config, Limits, LIMIT_DOCS};
use crate::events::{read, IssueState, STATES};
use crate::{drive, timer, Ctx};
use anyhow::Result;
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::io::Write;

/// #845: one Mermaid chart and its nodes that stand for a `[limits]` key (node id, key).
pub struct Chart {
    pub id: &'static str,
    pub source: String,
    pub nodes: Vec<(String, &'static str)>,
}

/// #845: issues per `STATES` entry (`review(n)` counts every review round).
pub fn counts<'a>(states: impl Iterator<Item = &'a IssueState>) -> BTreeMap<&'static str, usize> {
    let mut m = BTreeMap::new();
    for s in states {
        if let Some((name, _)) = crate::events::state(&s.state) {
            *m.entry(*name).or_default() += 1;
        }
    }
    m
}

fn timing(key: &str) -> bool {
    ["_secs", "_millis", "_minutes", "_hours", "_days"]
        .iter()
        .any(|s| key.ends_with(s))
}

fn id(state: &str) -> String {
    state.split('(').next().unwrap_or(state).replace('-', "_")
}

/// #845: the issue statechart and the timers' pass chart, at `limits`, with `counts` per state when live.
pub fn charts(limits: &Limits, counts: Option<&BTreeMap<&str, usize>>) -> [Chart; 2] {
    let l = serde_json::to_value(limits).unwrap_or_default();
    let set = |k: &str| format!("{k} = {}", l[k]);
    let label = |text: &str| {
        let words = text.split(' ').map(|w| match LIMIT_DOCS.iter().find(|d| d.0 == w) {
            Some((k, _)) => set(k),
            None => w.to_string(),
        });
        words.collect::<Vec<_>>().join(" ")
    };
    let mut s = String::from("stateDiagram-v2\n    [*] --> queued\n");
    for (name, _) in STATES {
        let n = counts.map(|c| format!(" · {}", c.get(name).copied().unwrap_or_default()));
        let _ = writeln!(s, "    state \"{name}{}\" as {}", n.unwrap_or_default(), id(name));
    }
    for (from, to) in STATES {
        for (next, why) in *to {
            let _ = writeln!(s, "    {} --> {} : {}", id(from), id(next), label(why));
        }
        if to.is_empty() {
            let _ = writeln!(s, "    {} --> [*]", id(from));
        }
    }
    let mut p = String::from("flowchart TD\n");
    let mut links: Vec<(String, &str)> = vec![];
    for (i, (job, args)) in timer::JOBS.iter().enumerate() {
        let every = if args[0] == "drive" { "fast_secs" } else { "slow_secs" };
        let first = if i == 0 { "t0" } else { "d0" };
        let _ = writeln!(p, "    j{i}[\"{job}: herdsman {}\"] --> {first}", args.join(" "));
        links.push((format!("j{i}"), every));
    }
    for (pre, steps) in [("t", &timer::TICK_STEPS[..]), ("d", &drive::STEPS[..])] {
        for (i, (step, keys)) in steps.iter().enumerate() {
            let next = (i + 1 < steps.len()).then(|| format!(" --> {pre}{}", i + 1));
            let _ = writeln!(p, "    {pre}{i}[\"{step}\"]{}", next.unwrap_or_default());
            links.extend(keys.iter().map(|k| (format!("{pre}{i}"), *k)));
        }
    }
    let drive = timer::TICK_STEPS
        .iter()
        .position(|s| s.0 == "drive")
        .unwrap_or_default();
    let _ = writeln!(
        p,
        "    t{drive} --> d0\n    other[\"other timers: serve, hosts, store\"]"
    );
    let rest = LIMIT_DOCS
        .iter()
        .filter(|(k, _)| timing(k) && !links.iter().any(|l| l.1 == *k));
    links.extend(rest.map(|(k, _)| ("other".to_string(), *k)).collect::<Vec<_>>());
    let mut nodes: Vec<(String, &str)> = vec![];
    for (at, k) in links {
        let _ = writeln!(p, "    {at} -.- k_{k}([\"{}\"])", set(k));
        if !nodes.iter().any(|n| n.1 == k) {
            nodes.push((format!("k_{k}"), k));
        }
    }
    [
        Chart {
            id: "states",
            source: s,
            nodes: vec![],
        },
        Chart {
            id: "pass",
            source: p,
            nodes,
        },
    ]
}

/// #845: the charts as `docs/workflow.md` holds them.
pub fn markdown(charts: &[Chart; 2], at: &str) -> String {
    let mut m = format!(
        "# Workflow\n\nGenerated by `herdsman diagram` from the code's tables ({at}); CI fails when this file differs.\n\
        `herdsman diagram --live [FLEET]` adds each state's issues (of FLEET, else every fleet) at the config's values.\n"
    );
    for (c, title) in charts.iter().zip(["Issue states", "Timers and the drive pass"]) {
        let _ = write!(m, "\n## {title}\n\n```mermaid\n{}```\n", c.source);
    }
    m
}

/// #845: `herdsman diagram [--live] [fleet]`: default `[limits]`, or the config's and per-state counts with `--live`.
pub fn run(ctx: &Ctx, live: bool, fleet: Option<&str>, out: &mut dyn Write) -> Result<()> {
    if !live {
        return Ok(write!(
            out,
            "{}",
            markdown(&charts(&Limits::default(), None), "default `[limits]`")
        )?);
    }
    let cfg = Config::load(&ctx.config)?;
    fleet.map(|f| cfg.fleet(f)).transpose()?;
    let st = crate::events::fold(&read(&ctx.state)?);
    let n = counts(st.values().filter(|s| fleet.is_none_or(|f| s.fleet == f)));
    let at = format!("live: {} issues", fleet.unwrap_or("all fleets'"));
    Ok(write!(out, "{}", markdown(&charts(&cfg.limits, Some(&n)), &at))?)
}
